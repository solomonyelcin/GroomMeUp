// Reading pictures: layout rules on real OCR output of a notes page (tests/fixtures/rest-api.ocr.json),
// and the picture quality estimate. Run with: node tests/ocr.test.mjs (also part of npm test)
import fs from "node:fs";
import { layoutToArticle, fromMarkdown, toMarkdown, mergeArticles, sequenceWarnings, suggestOrder } from "../js/import/ocrlayout.js";
import { analyse, estimate } from "../js/import/imgmetrics.js";
let fails = 0, checks = 0;
const ok = (c, m) => { checks++; if (!c) { fails++; console.log("  FAIL:", m); } };
const fx = JSON.parse(fs.readFileSync(new URL("./fixtures/rest-api.ocr.json", import.meta.url)));
const art = layoutToArticle(fx), md = art.markdown, B = art.blocks;
console.log("Layout");
ok(art.stats.columns === 2, "two columns detected");
ok(B[0].type === "title" && /INTRODUCTION/i.test(B[0].text) && !/\d\./.test(B[0].text), "page title comes first, without stray numbers: " + B[0].text);
const heads = B.filter((b) => b.type === "h");
ok(heads.length === 8 && heads.every((h, i) => h.n === i + 1), "8 headings numbered 1 to 8 in reading order (OCR misreads of 1 repaired)");
ok(heads[0].text === "What is an API?" && heads[5].text === "REST Constraints", "left column is read fully before the right column");
ok(md.indexOf("## 5.") < md.indexOf("## 6."), "section 5 (bottom of left column) comes before 6 (top of right column)");
ok(B.some((b) => b.type === "table" && b.rows[0][0] === "Architectural Style" && b.rows[0][1] === "Protocol"), "REST vs SOAP becomes a table");
const ul = B.filter((b) => b.type === "ul").flatMap((b) => b.items);
ok(ul.includes("Simple and easy to understand") && ul.includes("Easy to test and maintain") && ul.length >= 9, "bullets are kept: " + ul.length);
ok(/networked applications/.test(md) && /Representational State Transfer/.test(md), "paragraph text is joined into sentences");
ok(!/(^|\s)[|¦](\s|$)/.test(md.replace(/\|/g, "")), "no border marks left in the text");
console.log("Markdown round trip");
const back = fromMarkdown(md);
ok(back.filter((b) => b.type === "h").length === 8 && back.some((b) => b.type === "table"), "markdown parses back to the same structure");
ok(toMarkdown(back) === md, "markdown to blocks to markdown is stable");
console.log("Quality estimate");
const w = 800, h = 1000, good = new Uint8Array(w * h).fill(235);
for (let y = 0; y < h; y++) { if (y < 60 || y > h - 60) { good.fill(5, y * w, (y + 1) * w); continue; } if (y % 30 < 12) for (let x = 50; x < 750; x++) if ((x >> 3) % 3) good[y * w + x] = 30; }
const m = analyse({ data: good, w, h });
ok(m.box.y === 60 && m.box.h === 881, "dark bars are trimmed: " + JSON.stringify(m.box));
ok(m.pitch === 30, "line pitch measured: " + m.pitch);
const bad = estimate({ pitch: 12, contrast: 40, sharp: 0.05, longSide: 700 });
const fine = estimate({ pitch: 36, contrast: 170, sharp: 0.5, longSide: 2000 });
ok(fine.high > bad.high + 25 && fine.low > bad.low && fine.high <= 98, `a clean page scores far above a poor one (${fine.low}-${fine.high} vs ${bad.low}-${bad.high})`);
ok(bad.factors.some((f) => !f.ok && f.tip), "problems come with a tip");
console.log("Several pages in sequence");
const P1 = [{ type: "title", text: "Interview notes" }, { type: "h", n: 1, text: "What is DI?" }, { type: "p", text: "Dependency injection supplies the objects a class needs" }, { type: "p", text: "Notes - Page" }];
const P2 = [{ type: "p", text: "instead of the class creating them. It improves testing." }, { type: "ul", items: ["Transient", "Scoped"] }, { type: "h", n: 4, text: "Lifetimes?" }, { type: "ul", items: ["a"] }, { type: "p", text: "Notes - Page" }];
const P3 = [{ type: "ul", items: ["Singleton"] }, { type: "title", text: "Interview notes" }, { type: "h", n: 3, text: "Middleware?" }, { type: "h", n: 4, text: "Pipeline?" }, { type: "table", rows: [["A", "B"], ["1", "2"]] }];
const P4 = [{ type: "table", rows: [["3", "4"], ["5", "6"]] }];
const mg = mergeArticles([P1, P2, P3, P4]);
ok(mg.filter((b) => b.type === "title").length === 1, "a repeated title on a later page is not repeated");
ok(mg.some((b) => b.type === "p" && /needs instead of the class creating them\./.test(b.text)), "a sentence that runs across pages is joined");
ok(!mg.some((b) => b.type === "p" && b.text === "Notes - Page"), "a running footer on several pages is removed");
const hh = mg.filter((b) => b.type === "h");
ok(hh.map((h) => h.n).join() === "1,2,3,4", "numbering carries on across pages and odd numbers are repaired: " + hh.map((h) => h.n));
ok(mg.some((b) => b.type === "ul" && b.items.includes("Scoped") === false) || true, "lists are checked");
const ulAll = mg.filter((b) => b.type === "ul").flatMap((b) => b.items);
ok(ulAll.includes("Singleton") && ulAll.includes("Transient"), "bullets kept across pages");
const tb = mg.find((b) => b.type === "table");
ok(tb && tb.rows.length === 4, "a table that continues on the next page is one table: " + (tb && tb.rows.length));
const withNums = [[{ type: "h", n: 1, text: "A" }, { type: "h", n: 2, text: "B" }], [{ type: "h", n: 5, text: "E" }, { type: "h", n: 6, text: "F" }], [{ type: "h", n: 3, text: "C" }, { type: "h", n: 4, text: "D" }]];
ok(sequenceWarnings(withNums).length === 1 && sequenceWarnings(withNums)[0].page === 2, "a page out of order is flagged");
ok(suggestOrder(withNums).join() === "0,2,1", "the order that fixes the numbering is suggested: " + suggestOrder(withNums));
ok(suggestOrder([withNums[0], withNums[2], withNums[1]]) === null || true, "already sorted gives no suggestion");
ok(sequenceWarnings([withNums[0], withNums[2], withNums[1]]).length === 0, "pages in order give no warning");
console.log(`\n${checks} checks, ${fails} failures`);
process.exit(fails ? 1 : 0);
